func TestRateLimitService_OAuth401WritesOnlyExpiresAt(t *testing.T) {
	repo := &rateLimitAccountRepoStub{}
	invalidator := &tokenCacheInvalidatorRecorder{}
	service := NewRateLimitService(repo, nil, &config.Config{}, nil, nil)
	service.SetTokenCacheInvalidator(invalidator)
	account := &Account{ID: 7, Platform: PlatformAnthropic, Type: AccountTypeOAuth,
		Credentials: map[string]any{"access_token": "old-token", "refresh_token": "r"}}

	shouldDisable := service.HandleUpstreamError(context.Background(), account, 401, http.Header{}, []byte("unauthorized"))

	require.True(t, shouldDisable)
	require.Zero(t, repo.wholeRowUpdates, "the request-time object must not be written back")
	require.Equal(t, 1, repo.mergeCalls)
	require.Equal(t, []string{"expires_at"}, keysOf(repo.lastMergePatch))
	// The token actually sent may come from the token cache, so the write is
	// not conditioned on this object's token.
	require.Equal(t, CredentialsGuard{}, repo.lastMergeGuard)
	require.Equal(t, 1, repo.tempCalls)
	require.Len(t, invalidator.accounts, 1)
	_, mutated := account.Credentials["expires_at"]
	require.False(t, mutated, "the shared request object is not modified")
}

func keysOf(m map[string]any) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}
